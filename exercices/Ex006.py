# Crie um algoritmo que leia um número e mostre o seu dobro, triplo e raiz quadrada.

print('\nInforme um número qualquer, mostraremos o seu dobro, triplo e raiz quadrada.')
n = float(input('\nNúmero: '))
print('\nO número informado foi {}, seu dobro é {:.2f}, seu triplo é {:.2f} e sua raiz quadrada é {:.2f}!'.format(n, n*2, n*3, n**(0.5)))
