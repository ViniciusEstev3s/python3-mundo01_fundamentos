# Faça um programa que leia um número inteiro e mostre na tela seu sucessor e antecessor.

print('\nInforme um número inteiro, mostraremos seu sucessor e antecessor.')
n = int(input('\nNúmero Inteiro: '))
print('\nO número informado foi {}! Seu sucessor é {}, e seu antecessor é {}.'.format(n, n+1, n-1))
