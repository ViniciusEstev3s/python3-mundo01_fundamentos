# Crie um script Python que leia dois números e tente mostrar a soma entre eles.

print('\nInforme dois números para que os próprios sejam somados.')
num1 = int(input('\nInforme o primeiro número: '))
num2 = int(input('\nInforme o segundo número: '))
print('\nA soma entre {} e {} resultou em {}!'.format(num1, num2, num1+num2))
